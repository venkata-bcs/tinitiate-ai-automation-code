"""
Fixed (non-AI) part of the Streamlit website: the app entry point and page navigation,
the theme, the contact-form storage (data/contacts.csv) and the site test script.

The agents only write the header/footer and the page files; everything that must always
work is generated here from the spec.
"""
import json
import re

from models import SiteSpec
from themes import THEMES

RESERVED_COMPONENTS = {"App", "Layout", "Contact"}


def normalize_spec(spec: SiteSpec) -> SiteSpec:
    """Make page names, routes and field names safe to use in generated code."""
    seen = set()
    for page in spec.pages:
        words = re.sub(r"[^A-Za-z0-9]", " ", page.component or page.name).split()
        name = "".join(w[0].upper() + w[1:] for w in words)   # keeps 'AboutUs' as is
        if not name or not name[0].isalpha():
            name = "Page" + name
        if name in RESERVED_COMPONENTS:
            name += "Page"
        while name in seen:
            name += "X"
        seen.add(name)
        page.component = name
        route = page.route.strip().strip("/").lower().replace(" ", "-")
        page.route = "/" + re.sub(r"[^a-z0-9-]", "", route)
    if spec.pages and not any(p.route == "/" for p in spec.pages):
        spec.pages[0].route = "/"
    spec.pages.sort(key=lambda p: p.route != "/")   # home page first
    spec.contact.route = "/contact"
    for f in spec.contact.fields:
        f.name = re.sub(r"[^a-z0-9]+", "_", f.name.lower()).strip("_") or "field"
    return spec


def allowed_paths(spec: SiteSpec):
    """Files the Developer agent is allowed to write."""
    return {"components/layout.py", spec.contact.file} | {p.file for p in spec.pages}


# ------------------------------------------------------------------ generated files
def app_py(spec: SiteSpec) -> str:
    pages = [
        f'    st.Page("{p.file}", title="{p.name}", default=True),' if p.route == "/" else
        f'    st.Page("{p.file}", title="{p.name}", url_path="{p.url_path}"),'
        for p in spec.pages
    ]
    pages.append(f'    st.Page("{spec.contact.file}", title="{spec.contact.name}", '
                 f'url_path="{spec.contact.url_path}"),')
    pages_code = "\n".join(pages)
    return f'''"""
{spec.site_name} - Streamlit website entry point.
Generated by scaffold.py. Run it with:  streamlit run app.py
"""
import streamlit as st

from components.layout import render_footer, render_header
from lib.theme import inject_css

st.set_page_config(page_title="{spec.site_name}", page_icon="✨", layout="wide",
                   initial_sidebar_state="collapsed")
inject_css()

PAGES = [
{pages_code}
]

page = st.navigation(PAGES, position="hidden")   # navigation is done by the header links
render_header()
page.run()
render_footer()
'''


