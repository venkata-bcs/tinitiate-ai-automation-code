def write_scaffold(spec: SiteSpec, theme_id: str, website_dir):
    """Write all fixed files. Agent-written files (layout and pages) are left alone."""
    config = {
        "site_name": spec.site_name,
        "theme": theme_id,
        "pages": [{"name": p.name, "file": p.file, "url_path": p.url_path} for p in spec.pages],
        "contact": {"name": spec.contact.name, "file": spec.contact.file, "url_path": spec.contact.url_path},
        "contact_fields": [f.model_dump() for f in spec.contact.fields],
    }
    files = {
        "app.py": app_py(spec),
        "lib/__init__.py": "",
        "lib/theme.py": theme_py(theme_id),
        "lib/storage.py": STORAGE_PY,
        "components/__init__.py": "",
        "tests/check_site.py": CHECK_SITE_PY,
        ".streamlit/config.toml": config_toml(theme_id),
        "site_config.json": json.dumps(config, indent=2) + "\n",
        "requirements.txt": "streamlit>=1.50\n",
        "data/.gitkeep": "",
        ".gitignore": "__pycache__/\ndata/contacts.test.csv\n",
    }
    website_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in files.items():
        target = website_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    # Remove page files from an earlier build whose pages are no longer in the spec
    keep = {p.split("/")[-1] for p in allowed_paths(spec) if p.startswith("pages/")}
    for old in (website_dir / "pages").glob("*.py"):
        if old.name not in keep:
            old.unlink()
